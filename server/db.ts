// PostgreSQL database for agent accounts, sessions and saved quotes (driver: node-postgres "pg").
//
// Connection (same names as the docker-compose / VpsSetup convention used by the other RetinueSoft apps):
//   DATABASE_URL                     full connection string, wins if set, e.g. postgres://user:pass@host:5432/airrex
//   or POSTGRES_HOST (default localhost), POSTGRES_PORT (default 5432), POSTGRES_DB (default airrex),
//      POSTGRES_USER (default postgres), POSTGRES_PASSWORD
//   POSTGRES_SSL=true                use TLS (managed/cloud databases)
//
// The schema is created/updated automatically on startup (migrate()). Changes must stay additive and
// idempotent: CREATE ... IF NOT EXISTS, ALTER TABLE ... ADD COLUMN IF NOT EXISTS.

import pg from 'pg';

const env = process.env;

export const pool = new pg.Pool(
  env.DATABASE_URL
    ? { connectionString: env.DATABASE_URL, ssl: env.POSTGRES_SSL === 'true' ? { rejectUnauthorized: false } : undefined }
    : {
        host: env.POSTGRES_HOST ?? 'localhost',
        port: Number(env.POSTGRES_PORT ?? 5432),
        database: env.POSTGRES_DB ?? 'airrex',
        user: env.POSTGRES_USER ?? 'postgres',
        password: env.POSTGRES_PASSWORD,
        ssl: env.POSTGRES_SSL === 'true' ? { rejectUnauthorized: false } : undefined,
        max: Number(env.POSTGRES_POOL_SIZE ?? 10),
        connectionTimeoutMillis: 5000,
      },
);

pool.on('error', (err) => console.error('postgres pool error:', err.message));

/** Run a query and return all rows. Parameters use $1, $2 … placeholders. */
export async function many<T = Record<string, unknown>>(sql: string, params: unknown[] = []): Promise<T[]> {
  const r = await pool.query(sql, params);
  return r.rows as T[];
}

/** Run a query and return the first row (or undefined). */
export async function one<T = Record<string, unknown>>(sql: string, params: unknown[] = []): Promise<T | undefined> {
  const r = await pool.query(sql, params);
  return r.rows[0] as T | undefined;
}

/** Run a statement and return the number of affected rows. */
export async function exec(sql: string, params: unknown[] = []): Promise<number> {
  const r = await pool.query(sql, params);
  return r.rowCount ?? 0;
}

/** Run several statements in one transaction. */
export async function tx<T>(fn: (client: pg.PoolClient) => Promise<T>): Promise<T> {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    const result = await fn(client);
    await client.query('COMMIT');
    return result;
  } catch (err) {
    await client.query('ROLLBACK').catch(() => {});
    throw err;
  } finally {
    client.release();
  }
}

const SCHEMA = `
  CREATE TABLE IF NOT EXISTS agents (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           text NOT NULL,
    password_hash   text NOT NULL,
    contact_name    text NOT NULL DEFAULT '',
    agency_name     text NOT NULL DEFAULT '',
    phone           text NOT NULL DEFAULT '',
    whatsapp        text NOT NULL DEFAULT '',
    address         text NOT NULL DEFAULT '',
    city            text NOT NULL DEFAULT '',
    gstin           text NOT NULL DEFAULT '',
    website         text NOT NULL DEFAULT '',
    logo            text NOT NULL DEFAULT '',          -- data: URL, small image
    brand_color     text NOT NULL DEFAULT '#0A1C34',
    ticket_footer   text NOT NULL DEFAULT '',
    default_markup  integer NOT NULL DEFAULT 0,        -- service charge per passenger, INR
    created_at      timestamptz NOT NULL DEFAULT now(),
    trial_ends_at   timestamptz NOT NULL,
    paid_until      timestamptz
  );
  ALTER TABLE agents ADD COLUMN IF NOT EXISTS gst_on_charge boolean NOT NULL DEFAULT false;
  -- { "default": 350, "6E": 400, ... } INR per passenger per flight leg
  ALTER TABLE agents ADD COLUMN IF NOT EXISTS payment_fees jsonb NOT NULL DEFAULT '{}'::jsonb;
  -- Service charge: fixed ₹ (default_markup) and/or % of the fare, combined by markup_mode.
  ALTER TABLE agents ADD COLUMN IF NOT EXISTS markup_percent numeric(5,2) NOT NULL DEFAULT 0;
  ALTER TABLE agents ADD COLUMN IF NOT EXISTS markup_mode text NOT NULL DEFAULT 'fixed';
  -- Upper limit (₹) for markup_mode 'range' (% of the fare kept between default_markup and markup_max).
  ALTER TABLE agents ADD COLUMN IF NOT EXISTS markup_max integer NOT NULL DEFAULT 0;

  -- Agency licence, managed by the site admin (rexl) on /site-admin:
  --   status: pending (new sign-up, waiting for activation) | active | suspended
  --   licence: plan/licence name; expiry: paid_until; grace_days: days of access after expiry.
  -- Agencies that existed before this column keep working ('active'); new sign-ups start 'pending'.
  ALTER TABLE agents ADD COLUMN IF NOT EXISTS status text NOT NULL DEFAULT 'active';
  ALTER TABLE agents ALTER COLUMN status SET DEFAULT 'pending';
  ALTER TABLE agents ADD COLUMN IF NOT EXISTS licence text NOT NULL DEFAULT '';
  ALTER TABLE agents ADD COLUMN IF NOT EXISTS grace_days integer NOT NULL DEFAULT 0;

  -- Agencies log in with their mobile number (10 digits); email is optional (contact only).
  ALTER TABLE agents ADD COLUMN IF NOT EXISTS mobile text;
  ALTER TABLE agents ALTER COLUMN email DROP NOT NULL;
  -- Existing agencies: login mobile from their phone number (each number once; others are set by the site admin).
  UPDATE agents a SET mobile = x.m
  FROM (
    SELECT DISTINCT ON (m) id, m FROM (
      SELECT id, right(regexp_replace(phone, '[^0-9]', '', 'g'), 10) AS m FROM agents WHERE mobile IS NULL
    ) t
    WHERE m ~ '^[6-9][0-9]{9}$' AND NOT EXISTS (SELECT 1 FROM agents b WHERE b.mobile = t.m)
    ORDER BY m, id
  ) x
  WHERE a.id = x.id;
  CREATE UNIQUE INDEX IF NOT EXISTS agents_mobile ON agents (mobile) WHERE mobile IS NOT NULL;

  -- Site admin (username rexl). The password is set once on /site-admin after deployment.
  CREATE TABLE IF NOT EXISTS site_admins (
    username        text PRIMARY KEY,
    password_hash   text NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now()
  );
  -- Each agency's own recent searches (last 8) and "My trips" (flights it continued to book, last 50).
  CREATE TABLE IF NOT EXISTS recent_searches (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_id        integer NOT NULL REFERENCES agents(id) ON DELETE CASCADE,
    origin          text NOT NULL,
    destination     text NOT NULL,
    travel_date     date NOT NULL,
    adults          integer NOT NULL,
    searched_at     timestamptz NOT NULL DEFAULT now(),
    UNIQUE (agent_id, origin, destination, travel_date, adults)
  );
  CREATE TABLE IF NOT EXISTS trips (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_id        integer NOT NULL REFERENCES agents(id) ON DELETE CASCADE,
    offer_id        text NOT NULL,
    saved_at        timestamptz NOT NULL DEFAULT now(),
    query           jsonb NOT NULL,
    offer           jsonb NOT NULL,
    UNIQUE (agent_id, offer_id)
  );

  CREATE TABLE IF NOT EXISTS admin_sessions (
    token_hash      text PRIMARY KEY,
    username        text NOT NULL REFERENCES site_admins(username) ON DELETE CASCADE,
    expires_at      timestamptz NOT NULL
  );
  CREATE UNIQUE INDEX IF NOT EXISTS agents_email_lower ON agents (lower(email));

  CREATE TABLE IF NOT EXISTS sessions (
    token_hash  text PRIMARY KEY,                      -- SHA-256 of the cookie token
    agent_id    integer NOT NULL REFERENCES agents(id) ON DELETE CASCADE,
    expires_at  timestamptz NOT NULL
  );
  CREATE INDEX IF NOT EXISTS sessions_agent ON sessions (agent_id);

  CREATE TABLE IF NOT EXISTS quotes (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_id        integer NOT NULL REFERENCES agents(id) ON DELETE CASCADE,
    customer_name   text NOT NULL DEFAULT '',
    customer_phone  text NOT NULL DEFAULT '',
    data            jsonb NOT NULL,                    -- query, flights, charge
    created_at      timestamptz NOT NULL DEFAULT now()
  );
  -- 'draft' = built but not sent yet, 'sent' = sent on WhatsApp / copied
  ALTER TABLE quotes ADD COLUMN IF NOT EXISTS status text NOT NULL DEFAULT 'sent';
  ALTER TABLE quotes ADD COLUMN IF NOT EXISTS updated_at timestamptz;
  CREATE INDEX IF NOT EXISTS quotes_agent_recent ON quotes (agent_id, (COALESCE(updated_at, created_at)) DESC);

  -- Agents' saved passengers. Passport details are encrypted (server/crypto.ts) and deleted after delete_after.
  CREATE TABLE IF NOT EXISTS passengers (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_id        integer NOT NULL REFERENCES agents(id) ON DELETE CASCADE,
    data_enc        text NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    delete_after    timestamptz NOT NULL
  );
  CREATE INDEX IF NOT EXISTS passengers_agent ON passengers (agent_id);
  CREATE INDEX IF NOT EXISTS passengers_delete_after ON passengers (delete_after);

  -- What travellers/agents report the airline actually charged, to improve AirRex's prices and fee rules.
  CREATE TABLE IF NOT EXISTS fare_reports (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_id        integer REFERENCES agents(id) ON DELETE SET NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    origin          text NOT NULL,
    destination     text NOT NULL,
    travel_date     date NOT NULL,
    adults          integer NOT NULL,
    airline_code    text NOT NULL,
    flight_numbers  text NOT NULL DEFAULT '',
    shown_total     integer NOT NULL,
    paid_total      integer NOT NULL,
    fare_type       text NOT NULL DEFAULT '',
    bag_kg          integer,
    bag_cost        integer,
    airline_fee     integer,
    other_fees      integer,
    notes           text NOT NULL DEFAULT ''
  );
  CREATE INDEX IF NOT EXISTS fare_reports_airline ON fare_reports (airline_code, created_at DESC);

  -- Price/fee lines recorded by the AirRex Helper extension on airline pages (never payment pages, no
  -- passenger data): what the airline really showed at each booking step for a flight AirRex listed.
  CREATE TABLE IF NOT EXISTS page_captures (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      timestamptz NOT NULL DEFAULT now(),
    origin          text NOT NULL,
    destination     text NOT NULL,
    travel_date     date NOT NULL,
    adults          integer NOT NULL,
    airline_code    text NOT NULL,
    flight_numbers  text NOT NULL DEFAULT '',
    shown_total     integer NOT NULL,
    host            text NOT NULL,
    path            text NOT NULL DEFAULT '',
    title           text NOT NULL DEFAULT '',
    heading         text NOT NULL DEFAULT '',
    lines           jsonb NOT NULL,          -- [{ text, amount }]
    helper_version  text NOT NULL DEFAULT ''
  );
  CREATE INDEX IF NOT EXISTS page_captures_airline ON page_captures (airline_code, created_at DESC);
  -- The payment page's fare breakdown (where e.g. IndiGo adds its convenience fee).
  ALTER TABLE page_captures ADD COLUMN IF NOT EXISTS payment_page boolean NOT NULL DEFAULT false;
`;

let migrated: Promise<void> | undefined;

/** Create/upgrade tables. Safe to call many times; runs once per process. */
export function migrate(): Promise<void> {
  migrated ??= (async () => {
    // Serialise concurrent starts (two app instances) with an advisory lock.
    await tx(async (c) => {
      await c.query('SELECT pg_advisory_xact_lock(727274)');
      await c.query(SCHEMA);
    });
  })().catch((err) => {
    migrated = undefined; // database not reachable yet: try again on the next call
    throw err;
  });
  return migrated;
}

